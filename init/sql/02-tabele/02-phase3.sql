   id_curs NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   cod_moneda_sursa VARCHAR2(10) NOT NULL,
   cod_moneda_destinatie VARCHAR2(10) NOT NULL,
   data_curs DATE NOT NULL,
   valoare_curs NUMBER(18, 6) NOT NULL CHECK (valoare_curs > 0),

   CONSTRAINT fk_curs_moneda_sursa
      FOREIGN KEY (cod_moneda_sursa)
      REFERENCES moneda (cod_moneda),
   
   CONSTRAINT fk_curs_moneda_destinatie
      FOREIGN KEY (cod_moneda_destinatie)
      REFERENCES moneda (cod_moneda)
);
