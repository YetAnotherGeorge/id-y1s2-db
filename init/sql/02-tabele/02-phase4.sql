/*
Tabel 08: **detinere_portofoliu** (*tabel asociativ*)
   - `id_portofoliu` (Foreign Key -> portofoliu.id_portofoliu)
   - `ticker` (Foreign Key -> simbol_bursier.ticker)
   - `cantitate` (NUMBER(14,4), NOT NULL, CHECK (cantitate >= 0))
   - `pret_mediu` (NUMBER(14,4), CHECK (pret_mediu >= 0))
   - `data_actualizare` (DATE, DEFAULT SYSDATE)
   - Primary Key compus: # (`id_portofoliu`, `ticker`)
*/

CREATE TABLE detinere_portofoliu (
   id_portofoliu NUMBER NOT NULL, -- portofoliu.id_portofoliu
   ticker VARCHAR2(10) NOT NULL, -- simbol_bursier.ticker
   cantitate NUMBER(14,4) NOT NULL CHECK (cantitate >= 0),
   pret_mediu NUMBER(14,4) NOT NULL CHECK (pret_mediu >= 0),
   data_actualizare DATE DEFAULT SYSDATE,

   -- primary key compus din id_portofoliu + ticker
   CONSTRAINT pk_detinere_portofoliu PRIMARY KEY (id_portofoliu, ticker),

   CONSTRAINT fk_detinere_portofoliu_id_portofoliu
      FOREIGN KEY (id_portofoliu)
      REFERENCES portofoliu (id_portofoliu),

   CONSTRAINT fk_detinere_portofoliu_ticker
      FOREIGN KEY (ticker)
      REFERENCES simbol_bursier (ticker)
);
