/*
- 11: **executie_ordin**
   - `id_executie` # (Primary Key)
   - `id_ordin` (Foreign Key -> ordin.id_ordin, NOT NULL)
   - `id_bursa` (Foreign Key -> bursa.id_bursa, NOT NULL)
   - `cantitate_executata` (NUMBER(14,4), NOT NULL, CHECK (cantitate_executata > 0))
   - `pret_executie` (NUMBER(14,4), NOT NULL, CHECK (pret_executie > 0))
   - `data_executie` (DATE, NOT NULL)
*/
CREATE TABLE executie_ordin (
   id_executie NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
   id_ordin NUMBER NOT NULL,
   id_bursa NUMBER NOT NULL,
   cantitate_executata NUMBER(14,4) NOT NULL CHECK (cantitate_executata > 0),
   pret_executie NUMBER(14,4) NOT NULL CHECK (pret_executie > 0),
   data_executie DATE NOT NULL,

   CONSTRAINT fk_executie_ordin_id_ordin
      FOREIGN KEY (id_ordin)
      REFERENCES ordin(id_ordin),

   CONSTRAINT fk_executie_ordin_id_bursa
      FOREIGN KEY (id_bursa)
      REFERENCES bursa(id_bursa)
);
